"""Core domain models. Pure: no I/O."""

from enum import StrEnum


class Severity(StrEnum):
    """DefenseClaw verdict severity, ordered LOW < MEDIUM < HIGH < CRITICAL."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"

    @property
    def rank(self) -> int:
        return _SEVERITY_RANK[self]


_SEVERITY_RANK: dict[Severity, int] = {
    Severity.LOW: 0,
    Severity.MEDIUM: 1,
    Severity.HIGH: 2,
    Severity.CRITICAL: 3,
}
